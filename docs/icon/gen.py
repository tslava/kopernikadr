"""Kopernikadr launcher icon: one design -> preview SVG, Android adaptive-icon vectors, a mask preview page.
Design units: a 100-unit square; corners of the viewfinder at 15..85 map to 50dp of the 108dp canvas."""
import math, os, sys

out = sys.argv[1]
PLUM = "#2d1b3d"
K = 0.714                      # design unit -> dp
T = 54 - 50 * K
k = float(os.environ.get("ICON_K", "1.45"))       # size of the sun/orbit/earth group
w = float(os.environ.get("ICON_W", "5"))          # viewfinder stroke, design units


def m(x, y):
    return (round(T + x * K, 2), round(T + y * K, 2))


def ms(v):
    return round(v * K, 3)


P = lambda x, y: (50 + (x - 50) * k, 50 + (y - 50) * k)
orbit_rx, orbit_ry = 22 * k, 15 * k
sun_r, glow_r = 8 * k, 10.5 * k
ghosts = [(P(31, 44), 3.6 * k, .30), (P(35, 39), 3.6 * k, .55)]
earth = (P(41, 36), 4 * k)
a, b, L, r = 15, 85, 13, 5
corner_paths = [f"M{a},{a+L} V{a+r} Q{a},{a} {a+r},{a} H{a+L}", f"M{b-L},{a} H{b-r} Q{b},{a} {b},{a+r} V{a+L}",
                f"M{b},{b-L} V{b-r} Q{b},{b} {b-r},{b} H{b-L}", f"M{a+L},{b} H{a+r} Q{a},{b} {a},{b-r} V{b-L}"]
n = 34
dots = [(50 + orbit_rx * math.cos(2 * math.pi * i / n), 50 + orbit_ry * math.sin(2 * math.pi * i / n)) for i in range(n)]
dot_r = 0.55 * k
ex, ey = m(*earth[0])
X0, Y0 = m(50, 50)
cont = (f"M{round(ex-ms(1.6*k/1.2),3)},{round(ey+ms(.3*k/1.2),3)} q{ms(1*k/1.2)},{-ms(1.6*k/1.2)} {ms(2.2*k/1.2)},{-ms(.6*k/1.2)} "
        f"q{ms(.6*k/1.2)},{ms(1.2*k/1.2)} {-ms(.4*k/1.2)},{ms(1.8*k/1.2)} z")


def svg_full():
    g = [f'<defs><linearGradient id="cg" gradientUnits="userSpaceOnUse" x1="15" y1="15" x2="85" y2="85">'
         f'<stop offset="0" stop-color="#ff6b6b"/><stop offset="1" stop-color="#ffa94d"/></linearGradient>'
         f'<radialGradient id="sun" gradientUnits="userSpaceOnUse" cx="{m(50-sun_r*.2,0)[0]}" cy="{m(0,50-sun_r*.3)[1]}" r="{ms(sun_r*1.2)}">'
         f'<stop offset="0" stop-color="#fffbe0"/><stop offset=".4" stop-color="#ffe066"/><stop offset="1" stop-color="#ffd43b"/></radialGradient>'
         f'<radialGradient id="earth" gradientUnits="userSpaceOnUse" cx="{m(earth[0][0]-1.5,0)[0]}" cy="{m(0,earth[0][1]-1.5)[1]}" r="{ms(earth[1]*1.3)}">'
         f'<stop offset="0" stop-color="#a5d8ff"/><stop offset=".55" stop-color="#4dabf7"/><stop offset="1" stop-color="#1c7ed6"/></radialGradient></defs>',
         f'<rect width="108" height="108" fill="{PLUM}"/>',
         f'<g transform="translate({T} {T}) scale({K})">']
    g += [f'<path d="{d}" fill="none" stroke="url(#cg)" stroke-width="{w}" stroke-linecap="round" stroke-linejoin="round"/>' for d in corner_paths]
    g.append('</g>')
    g += [f'<circle cx="{m(x,y)[0]}" cy="{m(x,y)[1]}" r="{ms(dot_r)}" fill="#fff" opacity=".7"/>' for x, y in dots]
    g.append(f'<circle cx="{X0}" cy="{Y0}" r="{ms(glow_r)}" fill="#ffe066" opacity=".25"/><circle cx="{X0}" cy="{Y0}" r="{ms(sun_r)}" fill="url(#sun)"/>')
    g += [f'<circle cx="{m(*c)[0]}" cy="{m(*c)[1]}" r="{ms(rr)}" fill="#4dabf7" opacity="{op}"/>' for c, rr, op in ghosts]
    g.append(f'<circle cx="{ex}" cy="{ey}" r="{ms(earth[1])}" fill="url(#earth)"/><path d="{cont}" fill="#69db7c" opacity=".9"/>')
    return '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108">' + ''.join(g) + '</svg>'


def circ(cx, cy, rr):
    return f"M{round(cx-rr,3)},{cy} a{rr},{rr} 0 1,0 {round(2*rr,3)},0 a{rr},{rr} 0 1,0 {round(-2*rr,3)},0 z"


def cm(x, y, rr):
    X, Y = m(x, y)
    return circ(X, Y, ms(rr))


BG = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Launcher background: plain night plum. Generated by docs/icon/gen.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="{PLUM}" android:pathData="M0,0h108v108h-108z"/>
</vector>
'''
FG = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Launcher foreground: viewfinder corners, sun, dotted orbit, Earth with onion-skin ghosts.
     Generated by docs/icon/gen.py; the corners sit at the edge of the 66dp safe zone. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <group android:translateX="{round(T,3)}" android:translateY="{round(T,3)}" android:scaleX="{K}" android:scaleY="{K}">
        <path android:strokeWidth="{w}" android:strokeLineCap="round" android:strokeLineJoin="round"
            android:pathData="{' '.join(corner_paths)}">
            <aapt:attr name="android:strokeColor">
                <gradient android:type="linear" android:startX="15" android:startY="15" android:endX="85" android:endY="85"
                    android:startColor="#FF6B6B" android:endColor="#FFA94D"/>
            </aapt:attr>
        </path>
    </group>
    <path android:fillColor="#FFFFFF" android:fillAlpha="0.7" android:pathData="{' '.join(cm(x,y,dot_r) for x,y in dots)}"/>
    <path android:fillColor="#FFE066" android:fillAlpha="0.25" android:pathData="{circ(X0,Y0,ms(glow_r))}"/>
    <path android:pathData="{circ(X0,Y0,ms(sun_r))}">
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial" android:centerX="{m(50-sun_r*.2,0)[0]}" android:centerY="{m(0,50-sun_r*.3)[1]}" android:gradientRadius="{ms(sun_r*1.2)}">
                <item android:offset="0" android:color="#FFFFFBE0"/>
                <item android:offset="0.4" android:color="#FFFFE066"/>
                <item android:offset="1" android:color="#FFFFD43B"/>
            </gradient>
        </aapt:attr>
    </path>
    <path android:fillColor="#4DABF7" android:fillAlpha="{ghosts[0][2]}" android:pathData="{cm(*ghosts[0][0],ghosts[0][1])}"/>
    <path android:fillColor="#4DABF7" android:fillAlpha="{ghosts[1][2]}" android:pathData="{cm(*ghosts[1][0],ghosts[1][1])}"/>
    <path android:pathData="{circ(ex,ey,ms(earth[1]))}">
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial" android:centerX="{m(earth[0][0]-1.5,0)[0]}" android:centerY="{m(0,earth[0][1]-1.5)[1]}" android:gradientRadius="{ms(earth[1]*1.3)}">
                <item android:offset="0" android:color="#FFA5D8FF"/>
                <item android:offset="0.55" android:color="#FF4DABF7"/>
                <item android:offset="1" android:color="#FF1C7ED6"/>
            </gradient>
        </aapt:attr>
    </path>
    <path android:fillColor="#69DB7C" android:fillAlpha="0.9" android:pathData="{cont}"/>
</vector>
'''

svg = svg_full()
open(os.path.join(out, 'icon-108.svg'), 'w').write(svg)
open(os.path.join(out, 'ic_launcher_background.xml'), 'w').write(BG)
open(os.path.join(out, 'ic_launcher_foreground.xml'), 'w').write(FG)

inner = svg.split('>', 1)[1].rsplit('</svg>', 1)[0]


def masked(shape, size, uid):
    clip = {'circle': '<circle cx="54" cy="54" r="36"/>', 'squircle': '<rect x="18" y="18" width="72" height="72" rx="22"/>',
            'rounded': '<rect x="18" y="18" width="72" height="72" rx="12"/>'}[shape]
    body = inner.replace('id="', f'id="{uid}').replace('url(#', f'url(#{uid}')
    return (f'<svg width="{size}" height="{size}" viewBox="18 18 72 72"><defs><clipPath id="m{uid}">{clip}</clipPath></defs>'
            f'<g clip-path="url(#m{uid})">{body}</g></svg>')


cells, i = '', 0
for shape, label in (('circle', 'круг (Lenovo / Pixel)'), ('squircle', 'сквиркл (Samsung)'), ('rounded', 'скруглённый квадрат')):
    row = ''
    for size in (160, 72, 48):
        i += 1
        row += masked(shape, size, f'u{i}')
    cells += f'<div class="row"><div class="lbl">{label}</div>{row}</div>'
title = os.environ.get("ICON_TITLE", "Финал")
open(os.path.join(out, 'final.html'), 'w').write(f'''<!doctype html><html lang="ru"><head><meta charset="utf-8"><title>Иконка</title><style>
body{{background:var(--agterm-background,Canvas);color:var(--agterm-foreground,CanvasText);font:14px -apple-system,system-ui,sans-serif;margin:0;padding:18px}}
h1{{font-size:18px;margin:0 0 4px}} p{{opacity:.75;margin:0 0 14px}}
.row{{display:flex;align-items:center;gap:18px;margin:10px 0}} .lbl{{width:170px;opacity:.8}}
.wall{{display:flex;gap:16px;padding:14px;border-radius:14px;background:linear-gradient(135deg,#2b6cb0,#553c9a);margin-top:14px;align-items:center}}
.wall span{{color:#fff;font-size:12px}}
button{{font:inherit;padding:8px 18px;border-radius:9px;cursor:pointer;border:0;background:var(--agterm-color-2,#2f9e44);color:#fff;font-weight:600;margin-top:14px}}
form{{display:flex;gap:8px;margin-top:12px}} input{{flex:1;font:inherit;padding:7px 10px;border-radius:9px;border:1px solid color-mix(in srgb,var(--agterm-foreground,CanvasText) 25%,transparent);background:transparent;color:inherit}}
</style></head><body><h1>{title}</h1>
<p>Адаптивная иконка Android на разных лаунчерах, размеры 160 / 72 / 48.</p>{cells}
<div class="wall">{masked('circle',64,'w1')}<span>Kopernikadr</span>{masked('squircle',64,'w2')}<span>на обоях</span></div>
<button type="button" data-agterm="session.overlay.submit" data-agterm-args='{{"value":"ok"}}'>Беру, ставь в приложение</button>
<form data-agterm="session.overlay.submit"><input name="value" placeholder="Или правка…"><button style="margin:0;background:var(--agterm-color-4,#3b82f6)">Отправить</button></form>
</body></html>''')
print('ok')

# ---------- standalone logo (the visible 72dp area with a rounded plum plate), for UI screens
body = inner.replace(f'<rect width="108" height="108" fill="{PLUM}"/>', f'<rect x="18" y="18" width="72" height="72" rx="16" fill="{PLUM}"/>')
open(os.path.join(out, 'logo.svg'), 'w').write(
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72">' + body.replace('id="', 'id="kl-').replace('url(#', 'url(#kl-') + '</svg>')
LOGO = FG.replace('<!-- Launcher foreground: viewfinder corners, sun, dotted orbit, Earth with onion-skin ghosts.\n     Generated by docs/icon/gen.py; the corners sit at the edge of the 66dp safe zone. -->',
                  '<!-- App logo for in-app screens: the launcher icon on a rounded plum plate. Generated by docs/icon/gen.py. -->')
LOGO = LOGO.replace('android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">',
                    'android:width="72dp" android:height="72dp" android:viewportWidth="108" android:viewportHeight="108">\n'
                    '    <clip-path android:pathData="M34,18 H74 A16,16 0 0 1 90,34 V74 A16,16 0 0 1 74,90 H34 A16,16 0 0 1 18,74 V34 A16,16 0 0 1 34,18 Z"/>\n'
                    f'    <path android:fillColor="{PLUM}" android:pathData="M0,0h108v108h-108z"/>', 1)
# crop to the visible area: shift the viewport by wrapping everything in a translated group is not possible for clip; use viewport crop
LOGO = LOGO.replace('android:viewportWidth="108" android:viewportHeight="108">\n    <clip-path',
                    'android:viewportWidth="108" android:viewportHeight="108">\n    <group android:translateX="-18" android:translateY="-18" android:scaleX="1.5" android:scaleY="1.5" android:pivotX="18" android:pivotY="18">\n    <clip-path', 1)
LOGO = LOGO.replace('</vector>', '    </group>\n</vector>')
open(os.path.join(out, 'logo.xml'), 'w').write(LOGO)
